import { test } from "@playwright/test";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

import { MODES, SURFACES, VR_LOCALE, WIDTHS, declaredCells } from "./surfaces";

/**
 * The coverage ledger, written from the same registry the captures come from.
 *
 * Two files, both committed:
 *
 * - `inventory.json` — every surface × width × mode cell, with the exact baseline path it must exist
 *   at. This is what `check-coverage.mjs` holds the disk to.
 * - `INVENTORY.md` — the same matrix in a form a human reads, plus the ragged edges: which surfaces
 *   are not captured at every width, and why.
 *
 * It is a Playwright test rather than a script so it cannot drift from the captures: same config,
 * same `testDir`, same registry, and `npm run vr:baseline` / `vr:compare` regenerate it as a side
 * effect of the run. There is deliberately no timestamp in either file — a ledger that changes on
 * every run is a ledger nobody can diff.
 *
 * This cell runs before the captures (Playwright orders files by name, and `inventory` sorts before
 * `visual`), so the ledger on disk always describes the run that is about to happen, not the one
 * before it.
 */
test("write the baseline inventory", () => {
    const here = path.dirname(fileURLToPath(import.meta.url));

    const cells = declaredCells();

    const inventory = {
        locale: VR_LOCALE,
        widths: [...WIDTHS],
        modes: [...MODES],
        surfaceCount: SURFACES.length,
        cellCount: cells.filter((cell) => ! cell.skipped).length,
        skippedCellCount: cells.filter((cell) => cell.skipped).length,
        surfaces: SURFACES.map((surface) => ({
            slug: surface.slug,
            label: surface.label,
            kind: surface.kind,
            anonymous: surface.anonymous,
            honoursDark: surface.honoursDark,
            darkNote: surface.darkNote ?? null,
            skip: surface.skip ?? null,
            widths: [...surface.widths],
            cells: surface.widths.length * MODES.length,
            skippedCells: surface.skip ? surface.widths.length * MODES.length : 0,
        })),
        cells,
    };

    fs.writeFileSync(path.join(here, "inventory.json"), `${ JSON.stringify(inventory, null, 4) }\n`);

    const rows = SURFACES.map((surface) => {
        const widths = WIDTHS.map((width) => (surface.widths.includes(width) ? String(width) : "—")).join(" | ");

        return `| \`${ surface.slug }\` | ${ surface.label } | ${ surface.kind } | ${ widths } | ${ surface.honoursDark ? "yes" : "**no**" } | ${ surface.widths.length * MODES.length } |`;
    });

    const fullCrossProduct = SURFACES.length * WIDTHS.length * MODES.length;

    const captured = cells.filter((cell) => ! cell.skipped);

    const skippedSurfaces = SURFACES.filter((surface) => surface.skip).map(
        (surface) =>
            `- \`${ surface.slug }\` (${ surface.widths.length * MODES.length } cells) — ${ surface.skip }`
    );

    const ragged = SURFACES.filter((surface) => surface.widths.length !== WIDTHS.length).map(
        (surface) =>
            `- \`${ surface.slug }\` is captured at ${ surface.widths.join(", ") } px only — the surface does not exist at the other widths on this layout${
                surface.slug === "sidebar" ? " (the desktop sidebar is `max-lg:hidden`)" : ""
            }.`
    );

    const noDark = SURFACES.filter((surface) => ! surface.honoursDark && ! surface.darkNote).map(
        (surface) => `- \`${ surface.slug }\` — ${ surface.label }`
    );

    const darkByCookieOnly = SURFACES.filter((surface) => ! surface.honoursDark && surface.darkNote).map(
        (surface) => `- \`${ surface.slug }\` — ${ surface.darkNote }`
    );

    const markdown = `<!-- Generated by visual/inventory.spec.ts from visual/surfaces.ts. Do not edit by hand. -->

# Visual-regression baseline inventory

Locale: **${ VR_LOCALE }** (asserted on every capture, never pinned — see \`visual/surfaces.ts\`).
Widths: ${ WIDTHS.join(", ") } px. Colour modes: ${ MODES.join(", ") }.

**${ captured.length } baselines** across **${ SURFACES.length - skippedSurfaces.length } of ${
        SURFACES.length
    } surfaces**
(${ fullCrossProduct } cells if every surface existed at every width; ${ cells.length - captured.length } declared
cells are skipped — see below).

| Surface | What it is | Capture | ${ WIDTHS.join(" | ") } | Dark? | Cells |
| ------- | ---------- | ------- | ${ WIDTHS.map(() => "---").join(" | ") } | ----- | ----- |
${ rows.join("\n") }

## Surfaces that are not captured at all three widths

${ ragged.length ? ragged.join("\n") : "- none" }

## Surfaces where the two colour modes are the same document

These render inside \`components/layouts/anonymous.blade.php\` (or the web form's own layout), whose
\`<html>\` tag carries no \`dark\` class and never reads the \`dark_mode\` cookie. Their \`dark:\`
utilities exist but no ancestor ever gets the class, so the light and dark baselines are
pixel-identical. Captured in both modes anyway, because the moment one of these pages gains dark
support the comparison has to show it:

${ noDark.length ? noDark.join("\n") : "- none" }

## Surfaces where the cookie changes the pixels without setting the class

Both baselines exist and they are different images, but for a reason other than the theme:

${ darkByCookieOnly.length ? darkByCookieOnly.join("\n") : "- none" }

## Surfaces declared but not captured

${ skippedSurfaces.length ? skippedSurfaces.join("\n") : "- none" }

## Baselines, by cell

\`check-coverage.mjs\` verifies every path below exists and is non-empty:

${ captured.map((cell) => `- \`${ cell.file }\``).join("\n") }
`;

    fs.writeFileSync(path.join(here, "INVENTORY.md"), markdown);

    test.expect(cells.length).toBeGreaterThan(0);
});
