<?php

/**
 * Prove that a restored database is a working CRM instance, not just a set of tables.
 *
 * This is the check half of `scripts/restore-rehearsal.sh`: that script restores a dump into a
 * throwaway database and then runs this file with DB_DATABASE pointed at it. Everything below reads
 * and writes ONLY that throwaway database.
 *
 * Why it exists: a row count is not proof. A dump can carry the right number of `users` rows and the
 * wrong bytes, and a restore can recreate every table and still leave the application unable to sign
 * anyone in. The password column of `users` is a bcrypt hash, so the honest check is bcrypt against a
 * row that came out of the dump -- which is exactly what this file does, in four steps:
 *
 *   1. every `users` row still carries a valid bcrypt hash (cost 10, 60 characters), read with
 *      password_get_info() -- this proves the dump carried the hash column byte-for-byte;
 *   2. a NEGATIVE control: the restored hash rejects a wrong password. A hash that accepts anything
 *      (or that is not a hash) fails here, so step 3 cannot pass by accident;
 *   3. a bcrypt round-trip: Hash::make() a rehearsal password, store it in the throwaway row, read the
 *      row back out of the database and Hash::check() the value that actually came back;
 *   4. a real login through the same guard the login controller uses -- Auth::guard('user')->attempt()
 *      -- followed by bouncer()->hasPermission('dashboard'), which resolves the restored `roles` row.
 *
 * The password it uses is generated by the caller and passed in BACKUP_REHEARSAL_PASSWORD. It is never
 * printed, never written to disk by this script, and never leaves the throwaway database.
 *
 * Usage (from scripts/restore-rehearsal.sh; run by hand only against a throwaway database):
 *   BACKUP_REHEARSAL_PASSWORD='<generated>' DB_DATABASE=krayin_backup_rehearsal \
 *     php scripts/verify-restored-login.php
 *
 * Required environment:
 *   DB_DATABASE                 the throwaway database. Its name MUST end in `_rehearsal`.
 *   BACKUP_REHEARSAL_PASSWORD   at least 8 characters.
 *
 * Refusals (all before the application boots):
 *   - DB_DATABASE is not set in the ENVIRONMENT (a value from .env alone would be the live database);
 *   - DB_DATABASE does not end in `_rehearsal`;
 *   - DB_DATABASE is the database .env names, or the database phpunit.xml pins, or a MySQL system
 *     schema;
 *   - bootstrap/cache/config.php exists: a cached config beats the environment, so the write below
 *     would land on whatever database the cache names instead of the throwaway one.
 *
 * Exit status: 0 when every check passes, non-zero (and no further writes) otherwise.
 *
 * @see scripts/restore-rehearsal.sh  the rehearsal that calls this
 * @see scripts/backup-db.sh          the dump this proof is about
 */

declare(strict_types=1);

use Illuminate\Contracts\Console\Kernel;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;

$basePath = dirname(__DIR__);

$fail = static function (string $message): never {
    fwrite(STDERR, "restored-login: FAIL: {$message}\n");
    exit(1);
};

$pass = static function (string $check, string $detail = ''): void {
    printf("restored-login: PASS  %-20s %s\n", $check, $detail);
};

// ------------------------------------------------------------------ guards
// Read BEFORE the application boots. After bootstrap Laravel has loaded .env into the environment,
// so a missing DB_DATABASE would silently become the live database and step 3 would write a password
// into a client's data.
$target = getenv('DB_DATABASE');
$password = getenv('BACKUP_REHEARSAL_PASSWORD');

if (! is_string($target) || trim($target) === '') {
    $fail('DB_DATABASE is not set in the environment. This script refuses to fall back to .env, which names the LIVE database - export the throwaway database explicitly.');
}

if (! is_string($password) || $password === '') {
    $fail('BACKUP_REHEARSAL_PASSWORD is not set. scripts/restore-rehearsal.sh generates one; do not run this by hand against a database you care about.');
}

if (strlen($password) < 8) {
    $fail('BACKUP_REHEARSAL_PASSWORD must be at least 8 characters.');
}

if (! str_ends_with($target, '_rehearsal')) {
    $fail("DB_DATABASE is '{$target}', which does not end in '_rehearsal'. This script WRITES a password into the users table, so the name must make it impossible to aim at a live database.");
}

foreach (['mysql', 'information_schema', 'performance_schema', 'sys'] as $system) {
    if ($target === $system) {
        $fail("DB_DATABASE is '{$target}', a MySQL system schema.");
    }
}

if (is_file($basePath.'/bootstrap/cache/config.php')) {
    $fail('bootstrap/cache/config.php exists and would ignore DB_DATABASE, so the write below could land on the cached database name instead of the throwaway one. Run: php artisan config:clear');
}

// The live and test names, read straight out of the files rather than through the application, so
// this comparison is independent of the config the application is about to load.
$envDatabase = '';
$envText = @file_get_contents($basePath.'/.env');
if (is_string($envText) && preg_match('/^DB_DATABASE=(.*)$/m', $envText, $m) === 1) {
    $envDatabase = trim(trim($m[1]), '"\'');
}
if ($envDatabase !== '' && $target === $envDatabase) {
    $fail("DB_DATABASE is '{$target}', the database .env names - that is the live instance.");
}

$testDatabase = '';
$phpunitText = @file_get_contents($basePath.'/phpunit.xml');
if (is_string($phpunitText) && preg_match('/name="DB_DATABASE"\s+value="([^"]+)"/', $phpunitText, $m) === 1) {
    $testDatabase = $m[1];
}
if ($testDatabase !== '' && $target === $testDatabase) {
    $fail("DB_DATABASE is '{$target}', the database phpunit.xml pins - the test suite owns that one.");
}

if (! is_file($basePath.'/vendor/autoload.php')) {
    $fail('vendor/ is missing. Run `composer install` first (or scripts/provision-dev.sh).');
}

require $basePath.'/vendor/autoload.php';

$app = require $basePath.'/bootstrap/app.php';

$app->make(Kernel::class)->bootstrap();

printf("restored-login: database '%s' (live is '%s', test is '%s'; this script writes to the rehearsal only)\n", $target, $envDatabase ?: 'unknown', $testDatabase ?: 'unknown');

// ---------------------------------------------------------------- check 1
// The dump carried every hash. password_get_info() describes what a stored value IS, so a truncated
// or double-escaped hash column fails here instead of at step 4, where the message would be "wrong
// password" and send the operator looking in the wrong place.
try {
    $users = DB::table('users')->get(['id', 'email', 'password', 'role_id', 'status']);
} catch (Throwable $e) {
    $fail('could not read the restored `users` table ('.$e->getMessage().').');
}

if ($users->isEmpty()) {
    $fail('the restored `users` table is empty - a database nobody can log into is not a usable backup.');
}

$badHashes = [];
foreach ($users as $user) {
    $info = password_get_info((string) $user->password);
    $isBcrypt = ($info['algoName'] ?? '') === 'bcrypt';
    $cost = $info['options']['cost'] ?? null;
    if (! $isBcrypt || $cost !== 10 || strlen((string) $user->password) !== 60) {
        $badHashes[] = $user->id;
    }
}
if ($badHashes !== []) {
    $fail(count($badHashes).' of '.$users->count().' restored `users` rows do not carry a bcrypt cost-10 hash (ids: '.implode(', ', $badHashes).'). The password column did not survive the dump intact.');
}
$pass('bcrypt hashes', $users->count().'/'.$users->count().' restored `users` rows carry a 60-character bcrypt cost-10 hash');

// The account the login below uses: a real administrator row out of the dump, not a new one.
$admin = $users->first(fn ($u) => (int) $u->role_id === 1 && (int) $u->status === 1);
if ($admin === null) {
    $fail('the restored database holds no active administrator (role_id = 1, status = 1), so there is no account to prove a login with.');
}
if (! filter_var((string) $admin->email, FILTER_VALIDATE_EMAIL)) {
    $fail("the restored administrator row id {$admin->id} has no valid email address, so it cannot be used to sign in.");
}

// ---------------------------------------------------------------- check 2
// Negative control. Without it, a "hash" that accepted everything would pass step 3.
$restoredHash = (string) $admin->password;
if (Hash::check('definitely-not-the-password-'.bin2hex(random_bytes(8)), $restoredHash)) {
    $fail("the restored hash for user id {$admin->id} accepts a wrong password - it is not a bcrypt hash of anything usable.");
}
$pass('negative control', "the restored hash for user id {$admin->id} rejects a wrong password");

// ---------------------------------------------------------------- check 3
// Round-trip through the database: what Hash::check() reads back is what the restore actually stored.
$freshHash = Hash::make($password);
DB::table('users')->where('id', $admin->id)->update(['password' => $freshHash, 'updated_at' => now()]);

$readBack = DB::table('users')->where('id', $admin->id)->value('password');
if (! is_string($readBack) || ! Hash::check($password, $readBack)) {
    $fail("Hash::check() rejected the rehearsal password read back from user id {$admin->id} after it was written - the restored table accepted the write but did not return a usable hash.");
}
if (Hash::check($password, $restoredHash)) {
    $fail('the rehearsal password matches the ORIGINAL restored hash, which means the update did not replace it (or the two hashes are the same value by accident). The check would prove nothing.');
}
$pass('bcrypt round-trip', 'Hash::check() accepts the rehearsal password against the row read back from the restored database, and the write replaced the old hash');

// ---------------------------------------------------------------- check 4
// The real login: the same guard, provider and session guard the login controller calls.
$email = (string) $admin->email;
try {
    $authenticated = Auth::guard('user')->attempt(['email' => $email, 'password' => $password], false);
} catch (Throwable $e) {
    $fail('Auth::guard(\'user\')->attempt() threw against the restored data ('.$e->getMessage().').');
}

if (! $authenticated) {
    $fail("Auth::guard('user')->attempt() refused the restored administrator (user id {$admin->id}). The dump restored, the row is there, and the login still does not work.");
}
$loggedIn = Auth::guard('user')->user();
if ($loggedIn === null || (int) $loggedIn->id !== (int) $admin->id) {
    $fail('attempt() returned true but the guard has no matching user - the session guard and the restored row disagree.');
}
$pass('guard login', "Auth::guard('user')->attempt() authenticated user id {$admin->id}");

// The role comes from the restored `roles` table through the restored `users.role_id`; a dump missing
// it would log the user in and then deny every screen.
try {
    $role = $loggedIn->role;
    $hasDashboard = bouncer()->hasPermission('dashboard');
} catch (Throwable $e) {
    $fail('the restored role/permission rows could not be resolved ('.$e->getMessage().').');
}

if ($role === null) {
    $fail("the restored administrator's role did not resolve (role_id = {$loggedIn->role_id}); the `roles` table did not restore.");
}
if (! $hasDashboard) {
    $fail("bouncer()->hasPermission('dashboard') denied the restored administrator, so the restored permission rows are not usable.");
}
$pass('role and permission', "role '{$role->name}' resolved and bouncer()->hasPermission('dashboard') is true");

Auth::guard('user')->logout();

printf("restored-login: OK database '%s', %d tables, %d users, administrator id %d signs in\n", $target, DB::table('information_schema.tables')->where('table_schema', $target)->count(), $users->count(), $admin->id);
